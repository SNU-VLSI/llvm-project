INODECC::CondCode INODEDAGToDAGISel::getINODECCForIntCC(ISD::CondCode CC) {
  switch (CC) {
  default:
    llvm_unreachable("Unsupported CondCode");
  case ISD::SETEQ:
    return INODECC::COND_EQ;
  case ISD::SETNE:
    return INODECC::COND_NE;
  case ISD::SETLT:
    return INODECC::COND_LT;
  case ISD::SETGE:
    return INODECC::COND_GE;
  }
}