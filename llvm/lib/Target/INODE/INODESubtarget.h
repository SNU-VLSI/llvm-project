#ifndef LLVM_LIB_TARGET_INODE_INODESUBTARGET_H
#define LLVM_LIB_TARGET_INODE_INODESUBTARGET_H

#include "INODEFrameLowering.h"
#include "INODEISelLowering.h"
#include "INODEInstrInfo.h"
#include "INODERegisterInfo.h"
#include "llvm/CodeGen/GlobalISel/CallLowering.h"
#include "llvm/CodeGen/GlobalISel/InstructionSelector.h"
#include "llvm/CodeGen/GlobalISel/LegalizerInfo.h"
#include "llvm/CodeGen/RegisterBankInfo.h"
#include "llvm/CodeGen/TargetFrameLowering.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "INODEGenSubtargetInfo.inc"

namespace llvm {
class StringRef;
class TargetMachine;

class INODESubtarget : public INODEGenSubtargetInfo {
  virtual void anchor();

  INODEInstrInfo InstrInfo;
  INODETargetLowering TLInfo;
  INODEFrameLowering FrameLowering;

  // GlobalISel related APIs.
  std::unique_ptr<CallLowering> CallLoweringInfo;
  std::unique_ptr<LegalizerInfo> Legalizer;
  std::unique_ptr<RegisterBankInfo> RegBankInfo;
  std::unique_ptr<InstructionSelector> InstSelector;

public:
  INODESubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                const TargetMachine &TM);

// Getters for SubtargetFeatures defined in tablegen
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                                        \
  bool GETTER() const { return ATTRIBUTE; }
#include "INODEGenSubtargetInfo.inc"

  // Automatically generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const TargetFrameLowering *getFrameLowering() const override { return &FrameLowering; }
  const INODEInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const INODERegisterInfo *getRegisterInfo() const override { return &InstrInfo.getRegisterInfo(); }
  const INODETargetLowering *getTargetLowering() const override { return &TLInfo; }

  // GlobalISEL
  const CallLowering *getCallLowering() const override { return CallLoweringInfo.get(); }

  const RegisterBankInfo *getRegBankInfo() const override { return RegBankInfo.get(); }

  const LegalizerInfo *getLegalizerInfo() const override { return Legalizer.get(); }

  InstructionSelector *getInstructionSelector() const override { return InstSelector.get(); }
};

} // end namespace llvm

#endif
